"""Predeclare physical AI decision-diversity experiment with persistent Kafka pause.

30 NEW independent configs across 5 physically measurable fault families and 3
difficulty strata, 2 configs per cell; 2 repetitions x 4 actions = 240
physical replays. Real fault outcomes are not generated by the planner.
"""
from __future__ import annotations

import hashlib
import json
import random
from collections import Counter
from pathlib import Path

from plan import ACTIONS, create_plan

SEED = 2026111462
SCHEMA = "predict-shield/persistent-five-family-ai-plan/1"
FAULTS = ("loss", "delay", "duplicate", "reorder", "consumer_paused")
STRATA = ("SIMPLE", "INTERACTION", "PARTIAL_VISIBILITY")
COUNTS = {"train": 18, "calibration": 6, "test": 6}


def digest(*parts: object) -> str:
    return hashlib.sha256("|".join(map(str,parts)).encode()).hexdigest()[:20]


def build() -> tuple[list[dict],list[dict]]:
    original,_ = create_plan(seed=SEED)
    rng=random.Random(SEED)
    selected=[]
    for stratum in STRATA:
        candidates=[x for x in original if x["complexity_stratum"]==stratum]
        rng.shuffle(candidates)
        if len(candidates)<10:
            raise ValueError("Not enough diverse fault conditions")
        for index,fault in enumerate(FAULTS):
            for cfg in candidates[index*2:index*2+2]:
                new={**cfg,"fault_mode":fault,"configuration_id":f"v31-five-{len(selected):03d}",
                     "pilot_registration_schema":SCHEMA,
                     "independently_configured_operating_condition":True}
                if fault=="consumer_paused" and new["fault_target"]=="enforcer-hidden":
                    new["fault_target"]="enforcer-a"
                selected.append(new)
    rng.shuffle(selected)
    assignments=[p for p,n in COUNTS.items() for _ in range(n)]
    rng.shuffle(assignments)
    configs=[];trials=[]
    for cfg,partition in zip(selected,assignments):
        cfg={**cfg,"partition":partition,"cache_ttl_ms":max(6500,cfg["cache_ttl_ms"]),
             "measurement_seconds":5}
        configs.append(cfg)
        for repeat in (0,1):
            order=list(ACTIONS)
            random.Random(int(digest(SEED,cfg["configuration_id"],repeat),16)).shuffle(order)
            for action in order:
                trials.append({
                    "run_id":"v31-five-run-"+digest(SEED,cfg["configuration_id"],repeat,action),
                    "configuration_id":cfg["configuration_id"],
                    "partition":partition,"action_id":action,
                    "repeat":repeat,
                    "initial_state_seed":digest(SEED,cfg["configuration_id"],repeat),
                    "execution_status":"PLANNED_NOT_EXECUTED",
                    "pilot_registration_schema":SCHEMA,
                })
    validate(configs,trials)
    return configs,trials


def validate(configs:list[dict],trials:list[dict])->None:
    if len(configs)!=30 or len(trials)!=240:
        raise ValueError("Expected thirty independent configurations and 240 planned physical trials")
    if Counter((x["fault_mode"],x["complexity_stratum"]) for x in configs)!={
            (f,s):2 for f in FAULTS for s in STRATA}:
        raise ValueError("Five physical fault families not independently balanced")
    if Counter(x["partition"] for x in configs)!=COUNTS:
        raise ValueError("Invalid prospective configuration-group split")
    byid={x["configuration_id"]:x for x in configs}
    if len(byid)!=30 or len({x["run_id"] for x in trials})!=240:
        raise ValueError("Duplicate configurations or actions")
    for cfg in configs:
        for rep in (0,1):
            rows=[t for t in trials if (t["configuration_id"],t["repeat"])==
                  (cfg["configuration_id"],rep)]
            if (len(rows)!=4 or set(t["action_id"] for t in rows)!=set(ACTIONS) or
                len({t["initial_state_seed"] for t in rows})!=1 or
                any(t["partition"]!=cfg["partition"] or
                    t["execution_status"]!="PLANNED_NOT_EXECUTED" for t in rows)):
                raise ValueError("Unpaired action trials, cross-partition leak, or invented status")


def save(path:Path)->None:
    cfg,trials=build()
    path.mkdir(parents=True,exist_ok=False)
    for name,rows in (("configurations.jsonl",cfg),("trials.jsonl",trials)):
        with (path/name).open("x") as out:
            for row in rows:out.write(json.dumps(row,sort_keys=True)+"\n")
    (path/"registration.json").write_text(json.dumps({
        "schema":SCHEMA,"seed":SEED,"independent_groups":30,
        "planned_physical_replays":240,"splits":COUNTS,
        "execution_state":"NOT_EXECUTED_AT_REGISTRATION",
        "separate_from_original_v3_and_unfrozen_six_family_v31":True,
        "authority_outage_excluded_unknown_truth_not_fabricated":True,
    },indent=2)+"\n")


if __name__=="__main__":
    import argparse
    p=argparse.ArgumentParser();p.add_argument("--output",type=Path,required=True)
    save(p.parse_args().output)
    print("PLANNED 30 independent configs / 240 physical trials; no outcomes produced")
